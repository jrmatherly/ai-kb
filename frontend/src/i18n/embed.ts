export const SUPPORTED_LOCALES = ['en-US'] as const
export type EmbedLocale = (typeof SUPPORTED_LOCALES)[number]

/** Isolated from the main app `locale` key so embed preview never hijacks admin UI language. */
export const EMBED_LOCALE_STORAGE_KEY = 'ai-kb-embed-locale'

/** Map host-provided locale strings to a supported embed locale tag. The UI ships in en-US only. */
export function normalizeEmbedLocale(_raw: string): EmbedLocale {
  return 'en-US'
}

export function readEmbedLocaleFromUrl(): string {
  if (typeof window === 'undefined') return ''
  return new URLSearchParams(window.location.search).get('locale')?.trim() || ''
}

export const EMBED_MESSAGES = messages

